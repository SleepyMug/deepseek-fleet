#!/usr/bin/env node
// Generates a package's code from its protos, run in the package's folder,
// which holds buf.yaml and buf.gen.yaml: `buf generate`, into src/gen; and,
// with --descriptors, src/gen/descriptors.ts, the schema as a
// FileDescriptorSet with its comments and every file it imports, as
// `buf build` makes it, for a service's server to register with.
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const buf = (...args) => execFileSync('buf', args, { stdio: ['ignore', 'inherit', 'inherit'] })

rmSync('src/gen', { recursive: true, force: true })
buf('generate')
if (process.argv.includes('--descriptors')) {
  const dir = mkdtempSync(join(tmpdir(), 'fleet-gen-'))
  try {
    buf('build', '--output', join(dir, 'descriptors.binpb'))
    const encoded = readFileSync(join(dir, 'descriptors.binpb')).toString('base64')
    writeFileSync('src/gen/descriptors.ts', [
      '// @generated by scripts/gen.mjs from proto/, with `buf build`: do not edit.',
      '',
      "import { fromBinary } from '@bufbuild/protobuf'",
      "import { type FileDescriptorSet, FileDescriptorSetSchema } from '@bufbuild/protobuf/wkt'",
      '',
      '/** The schema, with its comments and every file it imports. */',
      'export function descriptors(): FileDescriptorSet {',
      `  return fromBinary(FileDescriptorSetSchema, Buffer.from(${JSON.stringify(encoded)}, 'base64'))`,
      '}',
      '',
    ].join('\n'))
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}
